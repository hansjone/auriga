export function useAdminI18n() {
  const i18n = useI18n({ useScope: 'local', messages: { 'zh-CN': zh, en } });
  const state = (value?: string) =>
    !value
      ? i18n.t('unknown')
      : Object.hasOwn(zh.states, value)
        ? i18n.t(`states.${value}`)
        : value;
  return { ...i18n, state };
}
