package auriga.iam;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import auriga.common.context.TenantContext;
import auriga.iam.api.NetworkAuthority;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.HashSet;
import java.util.Set;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;

class NetworkClientSubjectsTest {
  /** Generated by the Go gateway's actual UpSubject/DownSubject/ReplyPrefix functions (b3a374f). */
  @Test
  void ticketHttpSubjectsMatchGoGatewayVectorsAcrossAll32Shards() throws Exception {
    var vectors =
        Json.MAPPER.readTree(
            Files.readString(Path.of("../../../contracts/network/fixtures/client-subjects.json")));
    var client = mock(IamNetworkClient.class);
    var controller = new IamNetworkClientController(client, new ContractSchemas());
    var mvc = MockMvcBuilders.standaloneSetup(controller).build();
    var node =
        new NetworkAuthority.Node(
            "1", "1", UUID.randomUUID().toString(), UUID.randomUUID().toString(), false);
    Set<String> shards = new HashSet<>();
    TenantContext.run(
        UUID.randomUUID(),
        () -> {
          for (var vector : vectors) {
            String raw = vector.path("ticket").asString();
            when(client.prepare("access", "1"))
                .thenReturn(
                    new NetworkAuthority.Ticket(
                        raw,
                        node,
                        "server-a",
                        Instant.parse("2026-01-01T00:00:30Z"),
                        Instant.parse("2026-01-01T01:00:00Z")));
            try {
              var response =
                  mvc.perform(
                          post("/api/iam/v1/network/tickets")
                              .header("Authorization", "Bearer access")
                              .contentType("application/json")
                              .content("{\"node\":\"1\"}"))
                      .andExpect(status().isOk())
                      .andReturn()
                      .getResponse();
              var json = Json.read(response.getContentAsString());
              for (String field : Set.of("ingress", "upSubject", "downSubject", "replyPrefix"))
                assertEquals(
                    vector.path(field).asString(),
                    json.path(field).asString(),
                    field + " for " + raw);
              String up = json.path("upSubject").asString();
              assertEquals(5, up.split("\\.").length);
              shards.add(up.split("\\.")[3]);
              assertEquals("no-store", response.getHeader("Cache-Control"));
            } catch (Exception failure) {
              throw new RuntimeException(failure);
            }
          }
        });
    assertEquals(32, vectors.size());
    assertEquals(Set.of("abcdefghijklmnopqrstuvwxyz234567".split("")), shards);
  }
}
