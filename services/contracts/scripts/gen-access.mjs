// Generation projection only. The unmodified Draft 2020-12 schema remains the
// runtime validation authority; OpenAPI models are not a schema validator.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const pascal = (name) => name[0].toUpperCase() + name.slice(1);

export function accessProjection(schema) {
  const models = {};
  function project(value, name) {
    if (value.$ref) return { $ref: value.$ref.replace('#/$defs/', '#/components/schemas/') };
    // A narrowed Origin allOf has the same generated fields as Origin. Its host
    // restriction is retained in the embedded, complete runtime schema.
    if (value.allOf?.[0]?.$ref) return project(value.allOf[0], name);
    if (value.oneOf) {
      const tagField = 'kind' in value.oneOf[0].properties ? 'kind' : 'mode';
      const mapping = {};
      models[name] = {
        oneOf: value.oneOf.map((branch) => {
          const tag = branch.properties[tagField].const;
          const projected = project(branch, name + tag.split('_').map(pascal).join(''));
          mapping[tag] = projected.$ref;
          return projected;
        }),
        discriminator: { propertyName: tagField, mapping },
      };
      return { $ref: '#/components/schemas/' + name };
    }
    const result = {};
    for (const key of ['description', 'type', 'format', 'minimum', 'maximum', 'minLength', 'maxLength', 'pattern', 'minItems', 'maxItems', 'uniqueItems', 'required', 'additionalProperties', 'enum']) {
      if (key in value) result[key] = value[key];
    }
    if ('const' in value) {
      result.type = Number.isInteger(value.const) ? 'integer' : typeof value.const;
      result.enum = [value.const];
    }
    if (!result.type && result.enum) result.type = typeof result.enum[0];
    if (result.type === 'integer') result.format = 'int32';
    if (value.items) result.items = project(value.items, name + 'Item');
    if (value.properties) {
      result.properties = Object.fromEntries(Object.entries(value.properties).map(([key, child]) => [key, project(child, name + pascal(key))]));
      models[name] = result;
      return { $ref: '#/components/schemas/' + name };
    }
    return result;
  }
  for (const [name, value] of Object.entries(schema.$defs)) {
    const projected = project(value, name);
    if (!models[name]) models[name] = projected;
  }
  project(schema, 'Access');
  return { openapi: '3.0.3', info: { title: 'Auriga deployment access models', version: '1' }, paths: {}, components: { schemas: models } };
}

export function embeddedSchema(source) {
  const literal = source.replaceAll('\r\n', '\n').replaceAll('`', '` + "`" + `');
  return '// Code generated by gen-access.mjs; DO NOT EDIT.\npackage deployment\n\n// AccessSchemaJSON returns the original deployment schema, without projection.\nfunc AccessSchemaJSON() string {\n\treturn `' + literal + '`\n}\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = readFileSync(path.join(root, 'contracts/deployment/access.schema.json'), 'utf8');
  const spec = accessProjection(JSON.parse(source));
  const output = path.join(root, 'infra/gen/deployment');
  // Only this dedicated generated directory is cleaned. Handwritten loader code
  // lives in deploymentconfig and cannot be removed by model regeneration.
  rmSync(output, { recursive: true, force: true });
  mkdirSync(output, { recursive: true });
  writeFileSync(path.join(output, 'schema_generated.go'), embeddedSchema(source));
  const bundled = path.join(root, 'services/contracts/target/bundled');
  mkdirSync(bundled, { recursive: true });
  writeFileSync(path.join(bundled, 'access.json'), JSON.stringify(spec, null, 2) + '\n');
}
